// Regenerates src/lib/brandMarks.ts from simple-icons.
//
// WHY GENERATE instead of importing simple-icons at runtime: the package holds
// 3,453 icons and we need 11. Committing the extracted paths makes the bundle
// cost exact and visible in review, removes any dependence on the bundler
// tree-shaking a barrel export correctly, and keeps simple-icons a
// devDependency — nothing in the shipped app imports it.
//
// Run: node scripts/gen-brand-marks.mjs   (then commit the result)
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

// Keyed by the store-link `name` values normalize.ts actually emits.
// "Official site" and "RAWG" are deliberately absent: the first has no brand,
// the second has no icon in simple-icons. Both fall back to a generic glyph.
const WANT = {
  "Steam": "siSteam",
  "GOG": "siGogdotcom",
  "Epic Games": "siEpicgames",
  "itch.io": "siItchdotio",
  "IMDb": "siImdb",
  "Reddit": "siReddit",
  "Discord": "siDiscord",
  "Wikipedia": "siWikipedia",
  "Trakt": "siTrakt",
  "TMDB": "siThemoviedatabase",
  "IGDB": "siIgdb",

  // Streaming + console marks for the "Available on" filter (2026-08-27).
  // ⚠️ simple-icons no longer ships Nintendo, Xbox, Disney+, Prime Video or
  // Hulu — checked, not assumed. Those fall back to BrandGlyph's globe with the
  // provider's name beside it, which is the component's designed behaviour, not
  // a bug to work around.
  "Netflix": "siNetflix",
  "HBO Max": "siHbomax",
  "Max": "siMax",
  "Apple TV": "siAppletv",
  "PlayStation": "siPlaystation",
  "Paramount+": "siParamountplus",
  "Crunchyroll": "siCrunchyroll",
};

const entries = [];
for (const [name, key] of Object.entries(WANT)) {
  const icon = si[key];
  if (!icon) throw new Error(`simple-icons has no export "${key}" for "${name}" — check the slug`);
  entries.push(`  ${JSON.stringify(name)}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify("#" + icon.hex)}, path: ${JSON.stringify(icon.path)} },`);
}

const out = `// GENERATED by scripts/gen-brand-marks.mjs — do not edit by hand.
// Source: simple-icons (CC0-1.0 for the icon files; the marks themselves remain
// the trademarks of their respective owners and are used here only to label an
// outbound link to that service, which is nominative use).
//
// Only the store-link names normalize.ts emits are included. Re-run the script
// after adding a new one; it throws rather than silently skipping a bad slug.
//
// Every path is a 24x24 viewBox, single-path, fill-rule default.

export interface BrandMark {
  title: string;
  /** The brand's own colour. Used on hover only — see StoreLink. */
  hex: string;
  path: string;
}

export const BRAND_MARKS: Record<string, BrandMark> = {
${entries.join("\n")}
};
`;

writeFileSync(new URL("../src/lib/brandMarks.ts", import.meta.url), out);
console.log(`wrote ${entries.length} marks, ${out.length} bytes`);
